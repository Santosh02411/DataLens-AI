"""Automatic, explainable insight discovery.

Every finding here is computed with Pandas/NumPy and the tests in `stats.py`.
Nothing is generated by a language model. Each detector:

1. only runs when the dataset has the columns and the amount of data it needs,
2. applies a significance test or an explicit rule with stated thresholds,
3. corrects for the number of comparisons it tried (Bonferroni), and
4. returns the supporting statistics, method, steps, chart and evidence rows.

Where a finding maps onto an allowlisted operation, the chart and the
"open as analysis" action come from the existing validated execution layer.
"""

from __future__ import annotations

import math
import re
import time
from typing import Any, Callable

import numpy as np
import pandas as pd

from . import stats
from .executor import AGG_LABEL, _partial_periods, _period_labels, execute
from .operations import OperationError, parse_operation, validate_operation
from .profiling import AMOUNT_HINT, MAX_OUTLIER_SHARE, MIN_VALUES_FOR_OUTLIERS, MODZ_THRESHOLD, robust_bounds
from .utils import fmt_num, fmt_pct, jsonable, records

MAX_INSIGHTS = 8
KIND_CAPS = {
    "group_change": 2,
    "trend": 2,
    "group_difference": 2,
    "anomaly": 2,
    "period_anomaly": 1,
    "relationship": 2,
    "missing_pattern": 1,
    "data_quality": 2,
}
MIN_ROWS_FOR_TESTS = 30
SUM_HINT = re.compile(r"revenue|sales|amount|total|cost|spend|units|qty|quantity|fee|count", re.I)
MIN_GROUP_SIZE = 5
TEST_SAMPLE_ROWS = 100_000
EVIDENCE_ROWS = 15
GROUP_HINT = re.compile(r"region|country|state|city|market|segment|department|team|store|channel|category", re.I)

KIND_LABEL = {
    "group_change": "Change over time",
    "trend": "Trend",
    "period_anomaly": "Unusual period",
    "group_difference": "Group difference",
    "anomaly": "Unusual values",
    "relationship": "Relationship",
    "missing_pattern": "Missing data",
    "data_quality": "Data quality",
}


class Discovery:
    def __init__(self, df: pd.DataFrame, schema: dict[str, str], profile: dict[str, Any]):
        self.df = df
        self.schema = schema
        self.profile = profile
        self.n = len(df)
        self.dups = int(profile.get("duplicate_rows", 0))
        self.found: list[dict[str, Any]] = []
        self.checks: dict[str, int] = {}
        self.not_applicable: list[str] = []
        self.notes: list[str] = []
        self.col_profile = {c["name"]: c for c in profile.get("column_profiles", [])}

        self.numeric = [
            c for c, t in schema.items()
            if t == "numeric" and df[c].notna().sum() >= 3 and df[c].nunique() > 1
        ]
        cats = [c for c, t in schema.items() if t in ("categorical", "boolean") and 2 <= df[c].nunique() <= 30]
        self.cats = sorted(cats, key=lambda c: (0 if GROUP_HINT.search(c) else 1, df[c].nunique()))[:6]
        dates = [c for c, t in schema.items() if t == "datetime" and df[c].notna().sum() >= 10 and df[c].nunique() > 1]
        self.date = max(dates, key=lambda c: df[c].notna().sum()) if dates else None
        self.id_col = next((c for c, t in schema.items() if t == "identifier"), None)
        self.amounts = [c for c in self.numeric if AMOUNT_HINT.search(c)]
        self.primary = self._primary_metric()

        if self.n > TEST_SAMPLE_ROWS:
            self.test_df = df.sample(n=TEST_SAMPLE_ROWS, random_state=0)
            self.notes.append(f"Significance tests used a random sample of {TEST_SAMPLE_ROWS:,} of the {self.n:,} rows; charts and totals use every row.")
        else:
            self.test_df = df

    # ------------------------------------------------------------ helpers

    def _primary_metric(self) -> str | None:
        for pattern in (r"revenue|sales|amount|total", r"price|cost|value|spend"):
            for c in self.numeric:
                if re.search(pattern, c, re.I):
                    return c
        return self.numeric[0] if self.numeric else None

    def _bump(self, key: str, by: int = 1) -> None:
        self.checks[key] = self.checks.get(key, 0) + by

    def _run(self, op: dict[str, Any]) -> dict[str, Any] | None:
        """Run an allowlisted operation through the normal validation + execution path."""
        try:
            validated = validate_operation(parse_operation(op), self.df, self.schema)
            return execute(validated, self.df, self.schema, duplicate_rows=self.dups)
        except OperationError:
            return None

    def _label(self, idx: Any) -> str:
        if self.id_col is not None:
            v = self.df.at[idx, self.id_col]
            if pd.notna(v):
                return str(jsonable(v))
        return f"Row {int(idx) + 1}" if isinstance(idx, (int, np.integer)) else str(idx)

    def _evidence(self, rows: pd.DataFrame, note: str, total: int | None = None) -> dict[str, Any]:
        return {
            "columns": [str(c) for c in self.df.columns],
            "rows": records(rows, EVIDENCE_ROWS),
            "total_matching": int(len(rows) if total is None else total),
            "note": note,
        }

    def add(self, **kw: Any) -> None:
        kw.setdefault("caveats", [])
        kw.setdefault("operation", None)
        kw.setdefault("nature", "statistical")
        kw.setdefault("context", {})
        kw["kind_label"] = KIND_LABEL[kw["kind"]]
        kw["id"] = re.sub(r"[^a-z0-9]+", "-", f"{kw['kind']}-{'-'.join(kw['columns'])}".lower()).strip("-")
        self.found.append(kw)

    # ------------------------------------------------------------ time helpers

    def _granularity(self, dates: pd.Series, options=("month", "week", "quarter", "day"), min_periods=6, max_periods=60):
        """Pick the first granularity that yields enough *complete* periods. Returns (gran, start, end) or None."""
        for gran in options:
            first_partial, last_partial = _partial_periods(dates, gran)
            labels = _period_labels(dates, gran)
            unique = sorted(labels.unique())
            complete = [p for p in unique if p not in (first_partial, last_partial)]
            if min_periods <= len(complete) <= max_periods:
                return gran, complete
        return None

    # ------------------------------------------------------------ detectors

    def group_differences(self) -> None:
        if self.n < MIN_ROWS_FOR_TESTS:
            return
        metrics = [c for c in self.numeric if self.df[c].nunique() >= 3][:8]
        if not self.cats or not metrics:
            self.not_applicable.append("Group differences need at least one category column and one number column.")
            return
        results = []
        for cat in self.cats:
            for metric in metrics:
                frame = self.test_df[[cat, metric]].dropna()
                sizes = frame.groupby(cat, observed=True).size()
                keep = sizes[sizes >= MIN_GROUP_SIZE].index
                frame = frame[frame[cat].isin(keep)]
                if frame[cat].nunique() < 2:
                    continue
                kw = stats.kruskal_wallis(frame[metric], frame[cat])
                if kw is None:
                    continue
                results.append((kw, cat, metric))
        m = len(results)
        self._bump("group comparisons", m)
        best_per_metric: dict[str, tuple] = {}
        for kw, cat, metric in results:
            p_adj = min(1.0, kw.p * m)
            if p_adj >= 0.01 or kw.epsilon_sq < 0.01:
                continue
            if kw.epsilon_sq > 0.9:
                continue  # near-deterministic (e.g. price fixed by product): true but not a finding
            if metric not in best_per_metric or kw.epsilon_sq > best_per_metric[metric][0].epsilon_sq:
                best_per_metric[metric] = (kw, cat, metric, p_adj)
        for kw, cat, metric, p_adj in best_per_metric.values():
            full = self.df[[cat, metric]].dropna()
            g = full.groupby(cat, observed=True)[metric].agg(["mean", "median", "count"])
            g = g[g["count"] >= MIN_GROUP_SIZE].sort_values("mean", ascending=False)
            if len(g) < 2:
                continue
            hi, lo = g.index[0], g.index[-1]
            hi_v, lo_v = g.iloc[0]["mean"], g.iloc[-1]["mean"]
            strong = p_adj < 0.001 and kw.epsilon_sq >= 0.06
            level = "strong" if strong else "moderate"
            if lo_v > 0:
                gap = f"{hi_v / lo_v:.1f}× the {fmt_num(lo_v)} for {lo}"
            else:
                gap = f"{fmt_num(hi_v - lo_v)} more than {lo} ({fmt_num(lo_v)})"
            result = self._run({"type": "aggregate", "agg": "mean", "column": metric, "group_by": [cat], "sort": "desc", "limit": 15})
            if result is None:
                continue
            caveats = ["A difference between groups shows where values differ, not why. Other factors may explain it."]
            small = int((g["count"] < 30).sum())
            if small:
                caveats.append(f"{small} {cat} group(s) have fewer than 30 rows, so their averages are less stable.")
            self.add(
                kind="group_difference",
                context={"cat": cat, "group": jsonable(hi), "other": jsonable(lo), "metric": metric},
                level=level,
                score=45 + 30 * min(1.0, kw.epsilon_sq / 0.14) + (10 if strong else 0),
                columns=[cat, metric],
                title=f"{metric} differs by {cat}",
                finding=f"Average {metric} is highest for {hi} ({fmt_num(hi_v)}), {gap}. "
                f"The difference across {kw.k} {cat} groups is {'large and ' if kw.epsilon_sq >= 0.14 else ''}statistically clear.",
                stats=[
                    {"label": f"Highest average ({hi})", "value": jsonable(hi_v)},
                    {"label": f"Lowest average ({lo})", "value": jsonable(lo_v)},
                    {"label": "Kruskal–Wallis H", "value": round(kw.h, 2)},
                    {"label": "p-value (Bonferroni-adjusted)", "value": stats.fmt_p(p_adj)},
                    {"label": "Effect size ε²", "value": round(kw.epsilon_sq, 3)},
                    {"label": "Rows tested", "value": kw.n},
                ],
                method="Kruskal–Wallis rank test across groups, which is robust to skew and extreme values. Effect size is epsilon squared (0.01 small, 0.06 medium, 0.14 large).",
                steps=[
                    f"Compared {metric} across {kw.k} {cat} groups with at least {MIN_GROUP_SIZE} rows each.",
                    f"Kruskal–Wallis H = {kw.h:.2f}; adjusted for {m} comparisons tried: {stats.fmt_p(p_adj)}.",
                    f"Effect size ε² = {kw.epsilon_sq:.3f}. Reported because the adjusted p-value is below 0.01 and ε² is at least 0.01.",
                    *result["steps"],
                ],
                chart=result["chart"],
                evidence=result["evidence"],
                operation=result["operation"],
                caveats=caveats,
            )

    def _series(self, metric: str | None, agg: str, gran: str, complete: list[str]) -> pd.Series:
        cols = [self.date] + ([metric] if metric else [])
        d = self.df[cols].dropna()
        labels = _period_labels(d[self.date], gran)
        d = d.assign(_p=labels)
        d = d[d["_p"].isin(complete)]
        if metric is None:
            return d.groupby("_p").size().reindex(complete)
        return d.groupby("_p")[metric].agg(agg).reindex(complete)

    def _period_bounds(self, labels: list[str], gran: str) -> tuple[str, str]:
        dates = self.df[self.date].dropna()
        lab = _period_labels(dates, gran)
        inside = dates[lab.isin(labels)]
        return inside.min().strftime("%Y-%m-%d"), inside.max().strftime("%Y-%m-%d")

    def trends(self) -> None:
        if not self.date:
            self.not_applicable.append("No date column, so trends and changes over time weren't checked.")
            return
        dates = self.df[self.date].dropna()
        pick = self._granularity(dates)
        if pick is None:
            self.not_applicable.append(f"{self.date} doesn't span enough complete periods (at least 6) to test for trends.")
            return
        gran, complete = pick
        def agg_for(c: str) -> str:
            return "sum" if SUM_HINT.search(c) else "mean"

        others = [c for c in self.numeric if c != self.primary]
        series_specs: list[tuple[str | None, str]] = ([(self.primary, agg_for(self.primary))] if self.primary else []) + [(None, "count")]
        series_specs += [(c, agg_for(c)) for c in others]
        series_specs = series_specs[:6]
        lo, hi = self._period_bounds(complete, gran)
        self._trend_cache = []
        tests = []
        for metric, agg in series_specs:
            s = self._series(metric, agg, gran, complete).dropna()
            if len(s) < 6:
                continue
            mk = stats.mann_kendall(s.values)
            if mk is None:
                continue
            tests.append((metric, agg, s, mk))
            self._trend_cache.append((metric, agg, s))
        m = len(tests)
        self._bump("trend series", m)
        for metric, agg, s, mk in tests:
            p_adj = min(1.0, mk.p * m)
            median = float(np.median(s.values))
            rel = abs(mk.slope) * (len(s) - 1) / abs(median) if median else 0
            if p_adj >= 0.05 or rel < 0.10:
                continue
            label = "number of rows" if metric is None else f"{AGG_LABEL[agg]} {metric}"
            first, last = float(s.iloc[0]), float(s.iloc[-1])
            pct = (last - first) / abs(first) * 100 if first else None
            direction = "rose" if mk.slope > 0 else "fell"
            op = {"type": "trend", "date_column": self.date, "agg": agg, "value_column": metric, "granularity": gran,
                  "filters": [{"column": self.date, "op": "between", "value": [lo, hi]}]}
            result = self._run(op)
            if result is None:
                continue
            level = "strong" if p_adj < 0.001 else "moderate"
            self.add(
                kind="trend",
                context={"metric": metric, "agg": agg, "gran": gran, "date": self.date, "start": lo, "end": hi},
                level=level,
                score=55 + 30 * min(1.0, abs(mk.tau)) + (10 if level == "strong" else 0) + (8 if metric == self.primary else 2 if metric is None else 0),
                columns=[self.date] + ([metric] if metric else []),
                title=f"{label[0].upper() + label[1:]} {direction} over time",
                finding=f"The {label} {direction} fairly consistently, from {fmt_num(first)} in {s.index[0]} to {fmt_num(last)} in {s.index[-1]}"
                f"{f' ({fmt_pct(pct)})' if pct is not None else ''}. The typical change was {fmt_num(mk.slope)} per {gran}.",
                stats=[
                    {"label": f"First complete {gran}", "value": f"{s.index[0]}: {fmt_num(first)}"},
                    {"label": f"Last complete {gran}", "value": f"{s.index[-1]}: {fmt_num(last)}"},
                    {"label": f"Sen's slope (per {gran})", "value": jsonable(mk.slope)},
                    {"label": "Kendall's τ", "value": round(mk.tau, 3)},
                    {"label": "p-value (Bonferroni-adjusted)", "value": stats.fmt_p(p_adj)},
                    {"label": f"{gran.capitalize()}s analysed", "value": len(s)},
                ],
                method="Mann–Kendall test for a consistent upward or downward trend (doesn't assume a straight line or normal data). Size of the trend is Sen's slope, the median change per period.",
                steps=[
                    f"Calculated the {label} for each complete {gran} from {s.index[0]} to {s.index[-1]}; incomplete first or last periods were left out.",
                    f"Mann–Kendall τ = {mk.tau:.3f}; adjusted for {m} series tested: {stats.fmt_p(p_adj)}.",
                    f"Sen's slope = {fmt_num(mk.slope)} per {gran}. Reported because the adjusted p-value is below 0.05 and the overall change is at least 10% of the typical level.",
                ],
                chart=result["chart"],
                evidence=result["evidence"],
                operation=result["operation"],
                caveats=["A trend describes the past periods in this file. It isn't a forecast.",
                         *(["Seasonal businesses can show a trend inside one year that reverses the next."] if len(s) <= 12 and gran == "month" else [])],
            )
        self._gran = gran
        self._complete = complete

    def period_anomalies(self) -> None:
        cache = getattr(self, "_trend_cache", [])
        best = None
        tested = 0
        for metric, agg, s in cache:
            if len(s) < 8:
                continue
            y = s.values.astype(float)
            baseline = np.array([np.median(np.r_[y[max(0, i - 2):i], y[i + 1:i + 3]]) for i in range(len(y))])
            resid = y - baseline
            mad = float(np.median(np.abs(resid - np.median(resid)))) * 1.4826
            tested += 1
            if mad == 0:
                continue
            z = resid / mad
            for i in range(len(y)):
                rel = abs(resid[i]) / abs(baseline[i]) if baseline[i] else 0
                if abs(z[i]) >= 3.5 and rel >= 0.15 and (best is None or abs(z[i]) > abs(best[0])):
                    best = (z[i], metric, agg, s, i, baseline[i], rel)
        self._bump("periods checked for spikes", tested)
        if best is None:
            return
        z, metric, agg, s, i, base, rel = best
        period = s.index[i]
        obs = float(s.iloc[i])
        label = "number of rows" if metric is None else f"{AGG_LABEL[agg]} {metric}"
        gran = self._gran
        lo, hi = self._period_bounds(list(s.index), gran)
        result = self._run({"type": "trend", "date_column": self.date, "agg": agg, "value_column": metric, "granularity": gran,
                            "filters": [{"column": self.date, "op": "between", "value": [lo, hi]}]})
        if result is None:
            return
        chart = dict(result["chart"])
        chart["highlight_x"] = period
        d = self.df.loc[_period_labels(self.df[self.date].dropna(), gran).pipe(lambda x: x[x == period]).index]
        if metric:
            d = d.sort_values(metric, ascending=obs < base)
        word = "higher" if obs > base else "lower"
        self.add(
            kind="period_anomaly",
            context={"metric": metric, "agg": agg, "gran": gran, "date": self.date, "period": period, "start": lo, "end": hi},
            level="notable",
            score=45 + min(30, abs(z) * 3),
            columns=[self.date] + ([metric] if metric else []),
            title=f"{period} stands out for {label}",
            finding=f"In {period} the {label} was {fmt_num(obs)}, {rel * 100:.0f}% {word} than the {fmt_num(base)} expected from neighbouring {gran}s.",
            stats=[
                {"label": "Observed", "value": jsonable(obs)},
                {"label": f"Baseline (median of nearby {gran}s)", "value": jsonable(base)},
                {"label": "Difference", "value": f"{fmt_pct((obs - base) / abs(base) * 100)}"},
                {"label": "Robust z-score", "value": round(float(z), 2)},
            ],
            method=f"Each {gran} is compared with the median of up to two {gran}s on either side. Differences are scaled by the median absolute deviation (MAD); a robust z-score of 3.5 or more and a gap of at least 15% are flagged.",
            steps=[
                f"Calculated the {label} for each complete {gran}.",
                f"Baseline for {period}: median of the neighbouring {gran}s = {fmt_num(base)}.",
                f"Robust z-score = {float(z):.2f} (threshold 3.5).",
            ],
            chart=chart,
            evidence=self._evidence(d, f"Rows in {period}", len(d)),
            operation=result["operation"],
            nature="statistical_anomaly",
            caveats=["An unusual period is a prompt to investigate (a promotion, an outage, a data load issue), not proof of a problem."],
        )

    def group_changes(self) -> None:
        """A group whose period-over-period change departs sharply from the other groups.

        Gate 1 (size): change ≥ 20% and ≥ 25 points away from the median change of the other groups.
        Gate 2 (evidence): the group's share of rows must also shift between the two periods
        (chi-square test, Bonferroni-adjusted across every group/period comparison tried, p < 0.01).
        """
        if not self.date or not self.cats:
            return
        dates = self.df[self.date].dropna()
        pick = self._granularity(dates, options=("quarter", "month"), min_periods=2, max_periods=40)
        if pick is None:
            return
        gran, complete = pick
        metrics: list[tuple[str | None, str]] = [(c, "sum") for c in self.amounts[:3] if SUM_HINT.search(c)] + [(None, "count")]
        cands = []
        changes: dict[tuple, dict[tuple[str, str], float]] = {}
        tested = 0
        share_tests: set[tuple] = set()  # the row-share test depends only on counts: one test per (group, period pair)
        for cat in self.cats:
            d0 = self.df[[self.date, cat] + [m for m, _ in metrics if m]].dropna(subset=[self.date, cat])
            d0 = d0.assign(_p=_period_labels(d0[self.date], gran))
            d0 = d0[d0["_p"].isin(complete)]
            counts = d0.groupby(["_p", cat], observed=True).size().unstack(cat).fillna(0)
            for metric, agg in metrics:
                vals = counts if metric is None else d0.groupby(["_p", cat], observed=True)[metric].sum().unstack(cat).fillna(0)
                for a, b in zip(complete[:-1], complete[1:]):
                    if a not in vals.index or b not in vals.index:
                        continue
                    va, vb, na, nb = vals.loc[a], vals.loc[b], counts.loc[a], counts.loc[b]
                    total_a = va.sum()
                    eligible = [g for g in vals.columns if na[g] >= 10 and nb[g] >= 10 and va[g] > 0 and total_a > 0 and va[g] / total_a >= 0.05]
                    if len(eligible) < 3:
                        continue
                    pct = {g: (vb[g] - va[g]) / va[g] for g in eligible}
                    for g in eligible:
                        tested += 1
                        share_tests.add((cat, g, a, b))
                        changes.setdefault((cat, metric, g), {})[(a, b)] = pct[g]
                        med = float(np.median([pct[o] for o in eligible if o != g]))
                        dev = pct[g] - med
                        if abs(pct[g]) >= 0.20 and abs(dev) >= 0.25:
                            table = np.array([[na[g], na.sum() - na[g]], [nb[g], nb.sum() - nb[g]]])
                            chi = stats.chi2_independence(table)
                            if chi is None:
                                continue
                            cands.append(dict(dev=abs(dev), cat=cat, g=g, metric=metric, agg=agg, a=a, b=b, va=float(va[g]), vb=float(vb[g]),
                                              pct=pct[g], med=med, n_a=int(na[g]), n_b=int(nb[g]), p=chi[1]))
        self._bump("group period-over-period changes", tested)
        n_share_tests = max(len(share_tests), 1)
        for c in cands:
            c["p_adj"] = min(1.0, c["p"] * n_share_tests)
        cands = [c for c in cands if c["p_adj"] < 0.01]
        # A sharp move followed by an opposite move is one event (a dip or a spike): report the first move.
        cands.sort(key=lambda c: (complete.index(c["a"]), c["metric"] != self.primary, -c["dev"]))
        firsts = []
        seen_groups = set()
        for c in cands:
            key = (c["cat"], c["g"])
            if key in seen_groups:
                continue
            seen_groups.add(key)
            nxt_pair = next(((c["b"], complete[i + 1]) for i, p in enumerate(complete[:-1]) if p == c["b"]), None)
            rebound = changes.get((c["cat"], c["metric"], c["g"]), {}).get(nxt_pair) if nxt_pair else None
            c["rebound"] = (nxt_pair[1], rebound) if rebound is not None and np.sign(rebound) != np.sign(c["pct"]) and abs(rebound) >= 0.2 else None
            firsts.append(c)
        firsts.sort(key=lambda c: (-(c["metric"] == self.primary), -c["dev"]))
        added = 0
        for c in firsts:
            if added >= KIND_CAPS["group_change"]:
                break
            cat, g, metric, agg, a, b = c["cat"], c["g"], c["metric"], c["agg"], c["a"], c["b"]
            label = "number of rows" if metric is None else f"total {metric}"
            op = {"type": "period_change", "date_column": self.date, "agg": agg, "value_column": metric, "granularity": gran,
                  "period_a": a, "period_b": b, "group_by": cat, "sort": "asc" if c["pct"] < 0 else "desc"}
            result = self._run(op)
            if result is None:
                continue
            lab = _period_labels(self.df[self.date].dropna(), gran)
            rows = self.df.loc[lab[lab == b].index]
            rows = rows[rows[cat] == g]
            if metric:
                rows = rows.sort_values(metric, ascending=c["pct"] > 0)
            word = "fell" if c["pct"] < 0 else "rose"
            rebound_text = ""
            if c["rebound"]:
                period_c, r = c["rebound"]
                rebound_text = f" It {'recovered' if c['pct'] < 0 else 'dropped back'} in {period_c} ({fmt_pct(r * 100)})."
            stats_rows = [
                {"label": f"{g} in {a}", "value": jsonable(c["va"])},
                {"label": f"{g} in {b}", "value": jsonable(c["vb"])},
                {"label": f"Change for {g}", "value": fmt_pct(c["pct"] * 100)},
                {"label": f"Median change, other {cat} groups", "value": fmt_pct(c["med"] * 100)},
                {"label": f"Rows for {g} ({a} → {b})", "value": f"{c['n_a']:,} → {c['n_b']:,}"},
                {"label": "Share-of-rows shift (χ², adjusted)", "value": stats.fmt_p(c["p_adj"])},
            ]
            level = "strong" if c["p_adj"] < 0.001 else "moderate"
            self.add(
                kind="group_change",
                context={"cat": cat, "group": jsonable(g), "metric": metric, "agg": agg, "gran": gran, "date": self.date, "period_a": a, "period_b": b},
                level=level,
                score=62 + min(30, c["dev"] * 40) + (6 if metric == self.primary else 0),
                columns=[cat] + ([metric] if metric else []),
                title=f"{g}: {label} {word} {abs(c['pct']) * 100:.0f}% from {a} to {b}",
                finding=f"{g}'s {label} {word} {abs(c['pct']) * 100:.1f}% from {a} to {b} ({fmt_num(c['va'])} → {fmt_num(c['vb'])}), "
                f"while the other {cat} groups changed by a median of {fmt_pct(c['med'] * 100)}.{rebound_text}",
                stats=stats_rows,
                method=f"Each {cat} group (with at least 5% of the total and 10 rows per period) is compared across consecutive complete {gran}s. "
                f"Flagged when its change is at least 20% and 25 points away from the other groups' median, and its share of rows also shifts "
                f"(chi-square test, Bonferroni-adjusted for {n_share_tests:,} group/period comparisons, p < 0.01).",
                steps=[
                    f"Split {self.date} into {gran}s and kept complete ones only ({complete[0]} to {complete[-1]}).",
                    f"Calculated the {label} for each {cat} and {gran}, then the change from each {gran} to the next.",
                    f"{g}: {fmt_pct(c['pct'] * 100)} versus a median of {fmt_pct(c['med'] * 100)} for the others (gap {c['dev'] * 100:.0f} points).",
                    f"{g}'s share of rows changed from {a} to {b}: chi-square {stats.fmt_p(c['p_adj'])} after adjustment.",
                    *([f"The next {gran} moved the other way ({fmt_pct(c['rebound'][1] * 100)}), so this is reported as one event."] if c["rebound"] else []),
                ],
                chart=result["chart"],
                evidence=self._evidence(rows, f"{g} rows in {b}", len(rows)),
                operation=result["operation"],
                caveats=["Shows when and where a change happened, not why. Check for events such as stock-outs, pricing or a change in how data was recorded."],
            )
            added += 1

    def anomalies(self) -> None:
        scanned = 0
        fences: dict[str, tuple[float, float, str]] = {}
        details = []
        for c in self.numeric:
            v = self.df[c].dropna().astype(float)
            if len(v) < MIN_VALUES_FOR_OUTLIERS or v.nunique() < 5:
                continue
            scanned += 1
            b = robust_bounds(v)
            if b is None:
                self.notes.append(f"{c}: more than half the values are identical, so a robust spread can't be measured and unusual values weren't checked.")
                continue
            fences[c] = (b.lo, b.hi, b.scale)
            details.append((c, b.mask(self.df[c]), b.lo, b.hi, b.scale, len(v), float(v.median())))
        self._bump("number columns scanned for unusual values", scanned)

        selected_masks: list[pd.Series] = []
        cards = []
        for c, mask, lo, hi, method, n_valid, median in details:
            k = int(mask.sum())
            if k == 0:
                continue
            if k / n_valid > MAX_OUTLIER_SHARE:
                self.notes.append(f"{c}: {k:,} values ({100 * k / n_valid:.1f}%) sit far from the middle. That many looks like a genuine cluster or long tail rather than isolated anomalies, so it wasn't flagged.")
                continue
            flagged = self.df.loc[mask]
            dist = (flagged[c] - hi).where(flagged[c] > hi, lo - flagged[c]).abs()
            extremity = float((flagged[c].abs().max() / abs(hi)) if hi else 0)
            cards.append((extremity, c, mask, flagged.loc[dist.sort_values(ascending=False).index], lo, hi, method, n_valid, median))
        cards.sort(key=lambda x: -x[0])
        for extremity, c, mask, flagged, lo, hi, method, n_valid, median in cards:
            overlap = next((m for m in selected_masks if (m & mask).sum() >= 0.8 * mask.sum()), None)
            if overlap is not None:
                continue
            if len([f for f in self.found if f["kind"] == "anomaly"]) >= KIND_CAPS["anomaly"]:
                break
            selected_masks.append(mask)
            k = len(flagged)
            records_out = []
            for idx, row in flagged.head(10).iterrows():
                val = float(row[c])
                also = []
                for other, (olo, ohi, _) in fences.items():
                    if other == c or pd.isna(row[other]):
                        continue
                    ov = float(row[other])
                    if ov > ohi or ov < olo:
                        also.append(f"{other} = {fmt_num(ov)}")
                side = "above the upper limit" if val > hi else "below the lower limit"
                ratio = f"{val / median:.1f}× the median" if median > 0 and val > 0 else f"{fmt_num(val - median)} from the median"
                reason = f"{ratio} and {side} of {fmt_num(hi if val > hi else lo)}."
                if also:
                    reason += f" Also unusual in this record: {', '.join(also)}."
                records_out.append({"record": self._label(idx), "column": c, "observed": jsonable(val), "baseline_median": jsonable(median),
                                    "limit": jsonable(hi if val > hi else lo), "reason": reason})
            method_text = (
                f"Modified z-score (Iglewicz–Hoaglin), based on the median and the median absolute deviation, so the anomalies themselves can't distort the baseline. "
                + (f"Computed on a log scale because {c} is strongly right-skewed (typical for amounts and counts). " if method == "log" else "")
                + f"Values with |z| ≥ {MODZ_THRESHOLD} are flagged, which here means outside {fmt_num(lo)} to {fmt_num(hi)}."
            )
            chart = {
                "type": "bar",
                "x": "record",
                "series": [c],
                "data": [{"record": r["record"], c: r["observed"]} for r in records_out],
                "reference_lines": [{"y": hi, "label": "Upper limit"}, {"y": median, "label": "Median"}] if flagged[c].max() > hi else [{"y": median, "label": "Median"}],
            }
            op = {"type": "top_rows", "sort_by": c, "order": "desc" if flagged[c].iloc[0] > hi else "asc", "n": min(max(k, 1), 100),
                  "filters": [{"column": c, "op": "gt", "value": hi}] if flagged[c].iloc[0] > hi else [{"column": c, "op": "lt", "value": lo}]}
            result = self._run(op)
            top = records_out[0]
            self.add(
                kind="anomaly",
                context={"column": c, "lo": lo, "hi": hi, "side": "high" if flagged[c].iloc[0] > hi else "low"},
                level="notable",
                score=62 + min(25, 6 * math.log1p(extremity)),
                columns=[c],
                title=f"{k} unusual {c} value{'s' if k != 1 else ''}",
                finding=f"{k} of {n_valid:,} {c} values are far outside the typical range. The most extreme is {fmt_num(top['observed'])} "
                f"({top['record']}), compared with a median of {fmt_num(median)}.",
                stats=[
                    {"label": "Flagged values", "value": k},
                    {"label": "Median (baseline)", "value": jsonable(median)},
                    {"label": "Normal range", "value": f"{fmt_num(lo)} to {fmt_num(hi)}" if lo > self.df[c].min() else f"up to {fmt_num(hi)}"},
                    {"label": "Most extreme", "value": jsonable(top["observed"])},
                    {"label": "Share of values", "value": f"{100 * k / n_valid:.2f}%"},
                ],
                method=method_text,
                steps=[
                    f"Took the {n_valid:,} non-missing values of {c}.",
                    method_text,
                    f"{k} values fall outside that range; each is listed with its record, baseline and reason.",
                ],
                chart=chart,
                evidence=self._evidence(flagged, f"All {k} flagged records, most extreme first", k),
                anomalies=records_out,
                operation=result["operation"] if result else None,
                nature="statistical_anomaly",
                caveats=["Statistically unusual is not the same as wrong. These could be genuine (a bulk order, a large client) or entry errors; the data alone can't tell which."],
            )

    def data_quality(self) -> None:
        for c in self.amounts:
            v = self.df[c]
            neg = v < 0
            k = int(neg.sum())
            if k == 0 or k / max(v.notna().sum(), 1) >= 0.10:
                continue
            rows = self.df.loc[neg.fillna(False)].sort_values(c)
            total_neg = float(v[neg].sum())
            result = self._run({"type": "top_rows", "sort_by": c, "order": "asc", "n": min(k, 100), "filters": [{"column": c, "op": "lt", "value": 0}]})
            self.add(
                kind="data_quality",
                context={"column": c, "negatives": True},
                level="data_quality",
                score=35,
                columns=[c],
                title=f"{k} negative {c} value{'s' if k != 1 else ''}",
                finding=f"{k} rows have a negative {c} (together {fmt_num(total_neg)}). In a column like this they're often refunds or returns, but they could also be entry errors.",
                stats=[
                    {"label": "Negative values", "value": k},
                    {"label": "Their total", "value": jsonable(total_neg)},
                    {"label": "Smallest value", "value": jsonable(float(v.min()))},
                ],
                method=f"Counted values below zero in {c}, a column whose name suggests an amount or quantity.",
                steps=[f"Filtered {c} < 0: {k} rows."],
                chart={"type": "none"},
                evidence=self._evidence(rows, f"All {k} rows with negative {c}", k),
                operation=result["operation"] if result else None,
                nature="data_quality",
                caveats=["Not confirmed as errors. Check whether your source system records refunds as negative amounts."],
            )
        if self.dups:
            dup_extra = self.df.duplicated(keep="first")
            all_dups = self.df[self.df.duplicated(keep=False)]
            sort_cols = [c for c in self.df.columns if self.schema[c] in ("identifier", "datetime")][:2] or list(self.df.columns[:1])
            all_dups = all_dups.sort_values(sort_cols)
            stats_rows = [{"label": "Extra copies", "value": self.dups}, {"label": "Share of rows", "value": f"{100 * self.dups / self.n:.2f}%"}]
            impact = ""
            if self.primary:
                inflated = float(self.df.loc[dup_extra, self.primary].sum())
                total = float(self.df[self.primary].sum())
                stats_rows.append({"label": f"{self.primary} in extra copies", "value": jsonable(inflated)})
                if total:
                    impact = f" They add {fmt_num(inflated)} ({100 * inflated / total:.2f}%) to total {self.primary}."
            self.add(
                kind="data_quality",
                context={"duplicates": True},
                level="data_quality",
                score=40,
                columns=["duplicates"],
                title=f"{self.dups:,} exact duplicate rows",
                finding=f"{self.dups:,} rows are exact copies of another row, so counts and totals are slightly inflated.{impact}",
                stats=stats_rows,
                method="Rows that match another row in every column are counted as duplicates (the first occurrence is kept as the original).",
                steps=[f"Compared all {len(self.df.columns)} columns across {self.n:,} rows: {self.dups:,} extra copies."],
                chart={"type": "none"},
                evidence=self._evidence(all_dups, "Duplicated rows shown next to their copies", len(all_dups)),
                nature="data_quality",
                caveats=["Some datasets legitimately repeat rows (e.g. identical orders). If yours has a unique ID column, duplicates there are a stronger signal."],
            )

    def missing_patterns(self) -> None:
        if self.n < MIN_ROWS_FOR_TESTS:
            return
        candidates = [c for c in self.df.columns if 0.01 <= self.df[c].isna().mean() <= 0.6 and self.df[c].isna().sum() >= 20]
        if not candidates:
            return
        groupers: list[tuple[str, pd.Series]] = [(g, self.test_df[g]) for g in self.cats]
        if self.date:
            labels = _period_labels(self.test_df[self.date].dropna(), "month")
            if 2 <= labels.nunique() <= 60:
                groupers.append((f"month of {self.date}", labels.reindex(self.test_df.index)))
        tests = []
        for col in candidates:
            miss = self.test_df[col].isna()
            for name, g in groupers:
                if name == col:
                    continue
                frame = pd.DataFrame({"m": miss, "g": g}).dropna(subset=["g"])
                table = pd.crosstab(frame["g"], frame["m"]).reindex(columns=[False, True], fill_value=0)
                res = stats.chi2_independence(table.values)
                if res is None:
                    continue
                chi2, p, _ = res
                v = math.sqrt(chi2 / (len(frame) * (min(table.shape) - 1)))
                rates = table[True] / table.sum(axis=1)
                tests.append((col, name, p, v, rates, table))
        m = len(tests)
        self._bump("missing-value pattern tests", m)
        best = None
        for col, name, p, v, rates, table in tests:
            p_adj = min(1.0, p * m)
            if p_adj < 0.01 and v >= 0.1 and (best is None or v > best[3]):
                best = (col, name, p_adj, v, rates, table)
        if best:
            col, name, p_adj, v, rates, table = best
            top = rates.idxmax()
            overall = float(self.test_df[col].isna().mean())
            data = [{name: str(k), "missing %": round(100 * float(r), 1)} for k, r in rates.sort_values(ascending=False).head(15).items()]
            is_month = name.startswith("month of")
            if is_month:
                lab = _period_labels(self.df[self.date].dropna(), "month")
                rows = self.df.loc[lab[lab == top].index]
            else:
                rows = self.df[self.df[name] == top]
            rows = rows[rows[col].isna()]
            op = None if is_month else {"type": "aggregate", "agg": "count", "column": None, "group_by": [name], "filters": [{"column": col, "op": "is_null"}]}
            result = self._run(op) if op else None
            self.add(
                kind="missing_pattern",
                context={"column": col, "by": None if is_month else name, "top": jsonable(top)},
                level="strong" if p_adj < 0.001 and v >= 0.2 else "moderate",
                score=45 + min(30, v * 100),
                columns=[col, name],
                title=f"Missing {col} values cluster by {name}",
                finding=f"{col} is missing in {100 * rates.max():.1f}% of rows where {name} is {top}, versus {100 * overall:.1f}% overall. The gaps aren't random, so averages of {col} may be skewed.",
                stats=[
                    {"label": f"Missing where {name} = {top}", "value": f"{100 * rates.max():.1f}%"},
                    {"label": "Missing overall", "value": f"{100 * overall:.1f}%"},
                    {"label": "Cramér's V", "value": round(v, 3)},
                    {"label": "p-value (Bonferroni-adjusted)", "value": stats.fmt_p(p_adj)},
                ],
                method="Chi-square test of independence between 'value is missing' and each category (and month), adjusted for the number of tests. Cramér's V measures how strong the link is.",
                steps=[f"Tested {m} column/grouping combinations.", f"Strongest link: {col} vs {name}, V = {v:.3f}, {stats.fmt_p(p_adj)}."],
                chart={"type": "bar", "x": name, "series": ["missing %"], "data": data, "reference_lines": [{"y": round(100 * overall, 1), "label": "Overall"}]},
                evidence=self._evidence(rows, f"Rows where {name} is {top} and {col} is missing", len(rows)),
                operation=result["operation"] if result else None,
                caveats=["A pattern in missing values points at how the data was collected; it doesn't say the values were deleted on purpose."],
            )
        else:
            heavy = [c for c in candidates if self.df[c].isna().mean() >= 0.05]
            for col in heavy[:1]:
                rate = float(self.df[col].isna().mean())
                rows = self.df[self.df[col].isna()]
                checked = ", ".join([g for g, _ in groupers][:5])
                self.add(
                    kind="missing_pattern",
                    context={"column": col},
                    level="info",
                    score=20,
                    columns=[col],
                    title=f"Missing {col} values look random",
                    finding=f"{col} is missing in {100 * rate:.1f}% of rows, and the gaps are spread evenly across {checked}. Leaving them out is unlikely to bias results by those groups.",
                    stats=[{"label": "Missing", "value": f"{int(rows.shape[0]):,} ({100 * rate:.1f}%)"}, {"label": "Groupings tested", "value": len(groupers)}],
                    method="Chi-square tests between 'value is missing' and each category and month found no link (adjusted p ≥ 0.01 or Cramér's V < 0.1).",
                    steps=[f"Tested missingness of {col} against {len(groupers)} groupings; none showed a meaningful link."],
                    chart={"type": "none"},
                    evidence=self._evidence(rows, f"Rows with missing {col}", len(rows)),
                    caveats=["No link with these columns doesn't rule out a link with something not in the data."],
                )

    def relationships(self) -> None:
        if self.n < MIN_ROWS_FOR_TESTS:
            return
        cols = [c for c in self.numeric if self.schema[c] == "numeric"][:12]
        pairs = []
        for i, a in enumerate(cols):
            for b in cols[i + 1:]:
                if AMOUNT_HINT.search(a) and AMOUNT_HINT.search(b):
                    continue  # likely arithmetic (e.g. revenue = units × price)
                sub = self.test_df[[a, b]].dropna()
                if len(sub) < MIN_ROWS_FOR_TESTS or sub[a].nunique() < 3 or sub[b].nunique() < 3:
                    continue
                x, y = sub[a].astype(float), sub[b].astype(float)
                r = float(x.corr(y))
                rho = stats.spearman(x, y)
                if math.isnan(r) or math.isnan(rho):
                    continue
                pairs.append((a, b, r, rho, len(sub)))
        m = len(pairs)
        self._bump("number pairs correlated", m)
        hits = []
        for a, b, r, rho, n in pairs:
            p_adj = min(1.0, stats.pearson_p(r, n) * m)
            if abs(r) >= 0.3 and abs(r) <= 0.95 and p_adj < 0.001 and np.sign(r) == np.sign(rho) and abs(rho) >= 0.25:
                hits.append((abs(r), a, b, r, rho, n, p_adj))
        for _, a, b, r, rho, n, p_adj in sorted(hits, reverse=True)[: KIND_CAPS["relationship"]]:
            result = self._run({"type": "correlation", "column_x": a, "column_y": b, "method": "pearson"})
            if result is None:
                continue
            ci = {row["measure"]: row["value"] for row in result["result"]["rows"]}
            level = "strong" if abs(r) >= 0.5 else "moderate"
            self.add(
                kind="relationship",
                context={"x": a, "y": b},
                level=level,
                score=50 + 40 * min(1.0, abs(r)),
                columns=[a, b],
                title=f"{b} {'rises' if r > 0 else 'falls'} as {a} increases",
                finding=f"There is a {'strong' if abs(r) >= 0.5 else 'moderate'} {'positive' if r > 0 else 'negative'} relationship between {a} and {b} (r = {r:.2f} across {n:,} rows).",
                stats=[
                    {"label": "Pearson r", "value": round(r, 3)},
                    {"label": "Spearman ρ (rank check)", "value": round(rho, 3)},
                    {"label": "95% CI for r", "value": f"{ci.get('95% CI low'):.2f} to {ci.get('95% CI high'):.2f}" if ci.get("95% CI low") is not None else "n/a"},
                    {"label": "p-value (Bonferroni-adjusted)", "value": stats.fmt_p(p_adj)},
                    {"label": "Rows used", "value": n},
                ],
                method="Pearson correlation for every pair of number columns, confirmed with Spearman's rank correlation so a few extreme values can't drive the result. Pairs of amount columns are skipped because they're often arithmetically linked.",
                steps=[
                    f"Correlated {m} pairs of number columns.",
                    f"{a} vs {b}: r = {r:.3f}, ρ = {rho:.3f}, adjusted {stats.fmt_p(p_adj)}.",
                    "Reported because |r| ≥ 0.3, both measures agree in direction, and the adjusted p-value is below 0.001.",
                    *result["steps"],
                ],
                chart=result["chart"],
                evidence=result["evidence"],
                operation=result["operation"],
                caveats=["Correlation shows the two values move together, not that one causes the other."],
            )

    # ------------------------------------------------------------ orchestration

    def run(self) -> dict[str, Any]:
        t0 = time.perf_counter()
        if self.n < MIN_ROWS_FOR_TESTS:
            self.not_applicable.append(f"The dataset has {self.n} rows; statistical tests need at least {MIN_ROWS_FOR_TESTS}.")
        steps: list[Callable[[], None]] = [
            self.group_changes, self.trends, self.period_anomalies, self.group_differences,
            self.anomalies, self.relationships, self.missing_patterns, self.data_quality,
        ]
        for step in steps:
            step()
        if not self.numeric:
            self.not_applicable.append("No number columns, so there's nothing to measure for trends, differences or unusual values.")

        level_rank = {"strong": 3, "moderate": 2, "notable": 2, "data_quality": 1, "info": 0}
        ordered = sorted(self.found, key=lambda f: (-(f["score"] + 5 * level_rank[f["level"]])))
        selected, per_kind = [], {}
        for f in ordered:
            if f["level"] == "info":
                continue
            if per_kind.get(f["kind"], 0) >= KIND_CAPS[f["kind"]]:
                continue
            per_kind[f["kind"]] = per_kind.get(f["kind"], 0) + 1
            selected.append(f)
            if len(selected) >= MAX_INSIGHTS:
                break
        # Keep one slot for the top data-quality finding: it changes how every other number should be read.
        quality = [f for f in ordered if f["kind"] == "data_quality"]
        if quality and not any(f["kind"] == "data_quality" for f in selected):
            if len(selected) >= MAX_INSIGHTS:
                selected.pop()
            selected.append(quality[0])
        if len(selected) < MAX_INSIGHTS:
            selected += [f for f in ordered if f["level"] == "info"][: MAX_INSIGHTS - len(selected)]
        for f in selected:
            f["score"] = round(float(f["score"]), 1)
        total_checks = sum(self.checks.values())
        return jsonable({
            "insights": selected,
            "candidates_found": len(self.found),
            "checks": self.checks,
            "total_checks": total_checks,
            "not_applicable": self.not_applicable,
            "notes": self.notes,
            "rows": self.n,
            "elapsed_ms": int((time.perf_counter() - t0) * 1000),
        })


def discover_insights(df: pd.DataFrame, schema: dict[str, str], profile: dict[str, Any]) -> dict[str, Any]:
    return Discovery(df, schema, profile).run()


# ---------------------------------------------------------------- number guard for optional AI explanations

NUM_RE = re.compile(r"(?<![A-Za-z\d.])[-−]?\d[\d,]*(?:\.\d+)?%?")


def _numbers(text: str) -> list[float]:
    out = []
    for m in NUM_RE.findall(text):
        raw = m.replace("−", "-").replace(",", "").rstrip("%")
        try:
            out.append(float(raw))
        except ValueError:
            continue
    return out


def allowed_numbers(insight: dict[str, Any]) -> list[float]:
    parts = [insight.get("title", ""), insight.get("finding", ""), *(str(s.get("label", "")) + " " + str(s.get("value", "")) for s in insight.get("stats", []))]
    return _numbers(" ".join(parts))


def unsupported_numbers(text: str, allowed: list[float]) -> list[float]:
    """Numbers in `text` that don't match (within rounding) any number already in the insight."""
    bad = []
    for x in _numbers(text):
        if abs(x) <= 3 and float(x).is_integer():
            continue  # small counting words written as digits ("2 groups")
        if 1900 <= x <= 2100 and float(x).is_integer():
            continue  # years
        ok = any(abs(x - a) <= max(0.051, 0.006 * abs(a)) or abs(abs(x) - abs(a)) <= max(0.051, 0.006 * abs(a)) for a in allowed)
        if not ok:
            bad.append(x)
    return bad
